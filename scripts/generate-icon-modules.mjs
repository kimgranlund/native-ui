// generate-icon-modules.mjs
// Reads SVGs from @phosphor-icons/core and generates per-icon TypeScript modules.
// Usage: node scripts/generate-icon-modules.mjs

import { readFileSync, writeFileSync, rmSync, mkdirSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const ASSETS_DIR = join(import.meta.dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets');
const OUT_DIR = join(import.meta.dirname, '..', 'src', 'icons', 'phosphor');

// Weights to generate — regular is the default, fill provides solid variants.
const WEIGHTS = ['regular', 'fill'];

// Clean and recreate output directory
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const imports = [];
let total = 0;

for (const weight of WEIGHTS) {
  const dir = join(ASSETS_DIR, weight);
  const files = readdirSync(dir).filter(f => f.endsWith('.svg')).sort();

  for (const file of files) {
    const name = basename(file, '.svg');
    const raw = readFileSync(join(dir, file), 'utf-8');
    const svg = raw.replace(/\s*xmlns="[^"]*"/, '').trim();

    const module = [
      '// AUTO-GENERATED by scripts/generate-icon-modules.mjs — DO NOT EDIT',
      `import { registerIcon } from '../../registries/icon-registry.ts';`,
      `registerIcon('${name}', '${svg.replace(/'/g, "\\'")}');`,
      '',
    ].join('\n');

    writeFileSync(join(OUT_DIR, `${name}.ts`), module);
    imports.push(`import './${name}.ts';`);
    total++;
  }
}

// Barrel file
const barrel = [
  '// AUTO-GENERATED — imports ALL icons. Prefer per-icon imports for tree-shaking.',
  ...imports.sort(),
  '',
].join('\n');

writeFileSync(join(OUT_DIR, 'index.ts'), barrel);

console.log(`Generated ${total} icon modules (${WEIGHTS.join(', ')}) in src/icons/phosphor/`);
